-- ── 4. bookings.overseas_tour_package ───────────────────────────────────────
-- Needed for tcs_applicability = 'OVERSEAS_ONLY', the setting that actually matches the statute for
-- an agency selling both domestic and outbound. Per CBDT Circular 10/2023 a package qualifies only
-- if it bundles at least TWO of {international ticket, hotel, other similar expenditure} — a bare
-- international air ticket is not one — so this is an explicit judgement by the agent rather than
-- something inferred from the destination string.
--
-- Defaults false: an unclassified booking is treated as domestic, which under-collects rather than
-- over-collects. Over-collecting someone else's tax is the worse error, and the harder one to undo
-- once it has been remitted.
ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS overseas_tour_package boolean NOT NULL DEFAULT false;

